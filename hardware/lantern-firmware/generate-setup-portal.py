"""Embed the offline setup UI in firmware flash; no runtime asset server needed."""
from pathlib import Path
import json

root = Path(__file__).resolve().parent
pages = (
    ("lantern_setup_page_html", root / "main" / "setup-portal.html"),
    ("lantern_setup_saved_html", root / "main" / "setup-saved.html"),
)
output = ["// Generated by generate-setup-portal.py. Edit the HTML sources instead.", "#pragma once", ""]
for name, source in pages:
    html = source.read_text(encoding="utf-8")
    output.append(f"static const char {name}[] =")
    output.extend("    " + json.dumps(line, ensure_ascii=False) for line in html.splitlines(keepends=True))
    output[-1] += ";"
    output.append("")
(root / "main" / "lantern_setup_page.h").write_text("\n".join(output), encoding="utf-8")
for name, source in pages:
    print(f"{name}: {len(source.read_bytes())} bytes")
