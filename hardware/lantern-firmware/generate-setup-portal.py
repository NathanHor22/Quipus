"""Embed the offline setup UI in firmware flash; no runtime asset server needed."""
from pathlib import Path
import argparse
import json

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--check", action="store_true", help="Check the committed header without writing it")
args = parser.parse_args()
root = Path(__file__).resolve().parent
script = (root / "main" / "setup-return.js").read_text(encoding="utf-8")
pages = (
    ("lantern_setup_page_html", root / "main" / "setup-portal.html"),
    ("lantern_setup_saved_html", root / "main" / "setup-saved.html"),
)
output = ["// Generated by generate-setup-portal.py. Edit the HTML/JS sources instead.", "#pragma once", '#include "lantern_board.h"', ""]
for name, source in pages:
    html = source.read_text(encoding="utf-8").replace(
        "<!-- QUIPUS_SETUP_RETURN -->", "<script>\n" + script + "</script>")
    output.append(f"static const char {name}[] =")
    output.extend("    " + " LANTERN_API_BASE_URL ".join(
        json.dumps(part, ensure_ascii=False) for part in line.split("{{QUIPUS_WEB_ORIGIN}}"))
        for line in html.splitlines(keepends=True))
    output[-1] += ";"
    output.append("")
target = root / "main" / "lantern_setup_page.h"
rendered = "\n".join(output)
if args.check:
    if target.read_text(encoding="utf-8") != rendered:
        raise SystemExit("Setup header is stale. Run generate-setup-portal.py.")
else:
    target.write_text(rendered, encoding="utf-8")
for name, source in pages:
    print(f"{name}: {len(source.read_bytes())} bytes")
