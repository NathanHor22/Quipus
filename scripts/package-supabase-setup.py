"""Combine the ordered migrations for one-time setup in Supabase's SQL Editor."""
from __future__ import annotations

import argparse
import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "supabase/setup/quipus-fresh-project.sql"
UPGRADE_OUTPUT = ROOT / "supabase/setup/quipus-recording-calendar-upgrade.sql"


def render() -> str:
    files = sorted((ROOT / "supabase/migrations").glob("*.sql"))
    versions = [int(file.name.split("_", 1)[0]) for file in files]
    if not files or versions != list(range(1, len(files) + 1)):
        raise ValueError("Expected consecutive migrations beginning with 001")
    parts = [
        "-- QUIPUS: ONE-TIME SETUP FOR A FRESH SUPABASE PROJECT\n"
        "-- Generated by scripts/package-supabase-setup.py; do not edit this file.\n"
        "-- Paste this ENTIRE file into Supabase > SQL Editor > New query > Run.\n"
        "-- Prerequisite: Data API and Automatically expose new tables enabled.\n"
        "-- Existing/partially migrated projects must use only their missing migrations.\n"
        "-- Original migration contents and transaction boundaries are preserved.\n"
        "-- Stop on any error; earlier committed migrations may already be installed.\n"
        "-- SQL Editor execution does not populate the Supabase CLI migration ledger.\n\n"
        "do $quipus_fresh_project$\n"
        "begin\n"
        "  if to_regclass('auth.users') is null\n"
        "     or to_regclass('storage.buckets') is null\n"
        "     or to_regclass('storage.objects') is null then\n"
        "    raise exception 'Run this setup in your Supabase project SQL Editor';\n"
        "  end if;\n"
        "  if exists (select 1 from pg_class c join pg_namespace n on n.oid=c.relnamespace\n"
        "      where n.nspname='public' and c.relkind in ('r','p'))\n"
        "     or exists (select 1 from pg_type t join pg_namespace n on n.oid=t.typnamespace\n"
        "      where n.nspname='public' and t.typname='meeting_status') then\n"
        "    raise exception 'Fresh project required: existing public tables or Quipus types found. Apply only missing migrations instead';\n"
        "  end if;\n"
        "end\n"
        "$quipus_fresh_project$;\n"
    ]
    for file in files:
        parts.append(migration_block(file))
    parts.append(
        "\nselect 'Quipus database setup complete' as status,\n"
        "  (select count(*) from pg_class c join pg_namespace n on n.oid=c.relnamespace\n"
        "    where n.nspname='public' and c.relkind in ('r','p')) as application_tables,\n"
        "  (select not public from storage.buckets where id='recordings') as recordings_bucket_private;\n"
    )
    return "".join(parts)



def migration_block(file: Path) -> str:
    # Git may check out SQL as CRLF on Windows; keep hashes portable.
    data = file.read_bytes().replace(b"\r\n", b"\n")
    return (
        f"\n-- BEGIN MIGRATION {file.name}\n"
        f"-- Source SHA-256: {hashlib.sha256(data).hexdigest()}\n"
        + data.decode("utf-8")
        + f"\n-- END MIGRATION {file.name}\n"
    )


def render_recording_upgrade() -> str:
    parts = [
        "-- QUIPUS: EXISTING-PROJECT RECORDING AND CALENDAR UPGRADE (021 + 022)\n"
        "-- Generated by scripts/package-supabase-setup.py --recording-calendar-upgrade.\n"
        "-- Requires migrations 001-020 already installed. No credentials included.\n"
        "-- Run this ENTIRE file once in Supabase > SQL Editor > New query.\n"
        "-- This migration does not delete any existing recording or storage object.\n"
        "-- Future silence cleanup requires validated evidence and a processing lease.\n"
        "-- Calendar hiding preserves audio, transcripts, history and Google events.\n"
        "-- Stop on error: original migration transaction boundaries are preserved.\n"
        "-- SQL Editor does not populate the Supabase CLI migration ledger.\n\n"
        "do $quipus_recording_upgrade$\n"
        "begin\n"
        "  if to_regclass('public.lantern_sessions') is null\n"
        "     or to_regclass('public.recordings') is null\n"
        "     or to_regclass('public.recording_audio_sources') is null\n"
        "     or to_regclass('public.recording_audio_deletions') is null then\n"
        "    raise exception 'Install missing migrations 001-020 before this upgrade';\n"
        "  end if;\n"
        "  if to_regclass('public.recording_discard_decisions') is not null then\n"
        "    raise exception 'Migration 021 already exists: apply only missing migrations, such as 022';\n"
        "  end if;\n"
        "end\n"
        "$quipus_recording_upgrade$;\n"
    ]
    for name in ("021_short_silence_discard.sql", "022_recording_calendar_visibility.sql"):
        parts.append(migration_block(ROOT / "supabase/migrations" / name))
    parts.append(
        "\nselect 'Quipus recording and calendar upgrade complete' as status,\n"
        "  to_regclass('public.recording_discard_decisions') is not null as silence_policy_installed,\n"
        "  to_regclass('public.calendar_recording_preferences') is not null as calendar_visibility_installed;\n"
    )
    return "".join(parts)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if the bundle is stale")
    parser.add_argument("--recording-calendar-upgrade", action="store_true", help="Package only migrations 021 and 022 for an existing project")
    args = parser.parse_args()
    output = UPGRADE_OUTPUT if args.recording_calendar_upgrade else OUTPUT
    expected = render_recording_upgrade() if args.recording_calendar_upgrade else render()
    if args.check:
        if not output.exists() or output.read_text(encoding="utf-8") != expected:
            raise SystemExit(f"Setup SQL is stale. Regenerate {output.relative_to(ROOT)} with the matching packaging option")
        print(f"{output.name} matches its source migrations")
    else:
        output.parent.mkdir(parents=True, exist_ok=True)
        output.write_text(expected, encoding="utf-8", newline="\n")
        print(f"Wrote {output.relative_to(ROOT)} ({len(expected.encode('utf-8'))} bytes)")


if __name__ == "__main__":
    main()
