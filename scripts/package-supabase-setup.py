"""Combine the ordered migrations for one-time setup in Supabase's SQL Editor."""
from __future__ import annotations

import argparse
import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "supabase/setup/quipus-fresh-project.sql"


def render() -> str:
    files = sorted((ROOT / "supabase/migrations").glob("*.sql"))
    versions = [int(file.name.split("_", 1)[0]) for file in files]
    if not files or versions != list(range(1, len(files) + 1)):
        raise ValueError("Expected consecutive migrations beginning with 001")
    parts = [
        "-- QUIPUS: ONE-TIME SETUP FOR A FRESH SUPABASE PROJECT\n"
        "-- Generated by scripts/package-supabase-setup.py; do not edit this file.\n"
        "-- Paste this ENTIRE file into Supabase > SQL Editor > New query > Run.\n"
        "-- Prerequisite: Data API and Automatically expose new tables enabled.\n"
        "-- Existing/partially migrated projects must use only their missing migrations.\n"
        "-- Original migration contents and transaction boundaries are preserved.\n"
        "-- Stop on any error; earlier committed migrations may already be installed.\n"
        "-- SQL Editor execution does not populate the Supabase CLI migration ledger.\n\n"
        "do $quipus_fresh_project$\n"
        "begin\n"
        "  if to_regclass('auth.users') is null\n"
        "     or to_regclass('storage.buckets') is null\n"
        "     or to_regclass('storage.objects') is null then\n"
        "    raise exception 'Run this setup in your Supabase project SQL Editor';\n"
        "  end if;\n"
        "  if exists (select 1 from pg_class c join pg_namespace n on n.oid=c.relnamespace\n"
        "      where n.nspname='public' and c.relkind in ('r','p'))\n"
        "     or exists (select 1 from pg_type t join pg_namespace n on n.oid=t.typnamespace\n"
        "      where n.nspname='public' and t.typname='meeting_status') then\n"
        "    raise exception 'Fresh project required: existing public tables or Quipus types found. Apply only missing migrations instead';\n"
        "  end if;\n"
        "end\n"
        "$quipus_fresh_project$;\n"
    ]
    for file in files:
        data = file.read_bytes()
        parts.append(
            f"\n-- BEGIN MIGRATION {file.name}\n"
            f"-- Source SHA-256: {hashlib.sha256(data).hexdigest()}\n"
            + data.decode("utf-8")
            + f"\n-- END MIGRATION {file.name}\n"
        )
    parts.append(
        "\nselect 'Quipus database setup complete' as status,\n"
        "  (select count(*) from pg_class c join pg_namespace n on n.oid=c.relnamespace\n"
        "    where n.nspname='public' and c.relkind in ('r','p')) as application_tables,\n"
        "  (select not public from storage.buckets where id='recordings') as recordings_bucket_private;\n"
    )
    return "".join(parts)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if the bundle is stale")
    args = parser.parse_args()
    expected = render()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != expected:
            raise SystemExit("Setup SQL is stale. Run python scripts/package-supabase-setup.py")
        print("Fresh-project SQL matches all ordered migrations")
    else:
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT.write_text(expected, encoding="utf-8")
        print(f"Wrote {OUTPUT.relative_to(ROOT)} ({len(expected.encode('utf-8'))} bytes)")


if __name__ == "__main__":
    main()
