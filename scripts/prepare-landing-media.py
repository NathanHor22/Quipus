"""Prepare user-supplied prototype evidence and the Blender poster for the web.

Run using Python 3 with Pillow after scripts/build-landing-model.py.
Only the three explicitly supplied photographs are read.
"""
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "public" / "landing"
OUT.mkdir(parents=True, exist_ok=True)
PHOTOS = [
    ("prototype-components.webp", r"C:\Users\damna\Downloads\WhatsApp Image 2026-09-20 at 11.29.16(1).jpeg", (145,32,910,566)),
    ("prototype-in-use.webp", r"C:\Users\damna\Downloads\WhatsApp Image 2026-09-20 at 11.29.16.jpeg", (154,78,905,581)),
    ("prototype-rear.webp", r"C:\Users\damna\Downloads\WhatsApp Image 2026-09-20 at 11.29.14.jpeg", (19,199,670,980)),
]
for destination, source, crop in PHOTOS:
    if not Path(source).is_file():
        print("Photograph unavailable:", source)
        continue
    image = Image.open(source).convert("RGB").crop(crop)
    image.thumbnail((1200,1000), Image.Resampling.LANCZOS)
    image.save(OUT / destination, "WEBP", quality=86, method=6)
    print(destination, image.size, (OUT / destination).stat().st_size)
poster = OUT / "quipus-prototype.png"
if poster.is_file():
    image = Image.open(poster).convert("RGBA")
    image.save(OUT / "quipus-prototype.webp", "WEBP", quality=88, method=6)
    print("quipus-prototype.webp", image.size, (OUT / "quipus-prototype.webp").stat().st_size)
    poster.unlink()  # Regenerated by Blender; only the web-optimised poster is shipped.
